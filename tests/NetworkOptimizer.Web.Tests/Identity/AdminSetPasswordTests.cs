using System.Security.Claims;
using FluentAssertions;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using NetworkOptimizer.Storage.Models;
using NetworkOptimizer.Storage.Models.Identity;
using NetworkOptimizer.Web.Services;
using NetworkOptimizer.Web.Services.Auditing;
using NetworkOptimizer.Web.Services.Authorization;
using NetworkOptimizer.Web.Services.Identity;
using Xunit;

namespace NetworkOptimizer.Web.Tests.Identity;

/// <summary>
/// A password an administrator sets for someone else is one the administrator knows, so the account
/// must replace it before the session is worth anything. The built-in admin's auto-generated first-run
/// password carries the same flag but keeps its own banners and is never confined.
/// </summary>
public sealed class AdminSetPasswordTests : IDisposable
{
    private const string AdminSet = "Admin-Set-Pass-1";
    private const string Chosen = "Users-Own-Pass-2";

    private readonly string _dbPath = Path.Combine(Path.GetTempPath(), $"netopt-adminset-test-{Guid.NewGuid():N}.db");

    private async Task<ServiceProvider> BuildAsync(bool autoGeneratedAdmin = false)
    {
        var mainOptions = new DbContextOptionsBuilder<NetworkOptimizerDbContext>()
            .UseSqlite($"Data Source={_dbPath}")
            .Options;
        await using (var db = new NetworkOptimizerDbContext(mainOptions))
        {
            await db.Database.MigrateAsync();
            if (autoGeneratedAdmin)
            {
                // Enabled=false is the auto-generated first-run password, which the seed flags temporary.
                db.AdminSettings.Add(new AdminSettings { Password = new PasswordHasher().HashPassword(AdminSet), Enabled = false });
                await db.SaveChangesAsync();
            }
        }

        var services = new ServiceCollection();
        services.AddLogging();
        services.AddDataProtection();
        services.AddSingleton<IDbContextFactory<NetworkOptimizerDbContext>>(new NetworkOptimizerDbContextFactory(mainOptions));
        services.AddNetOptIdentityCore(_dbPath);
        services.AddSingleton<IAuditLogger>(new NoOpAuditLogger());
        services.AddScoped<ICallerContext, CallerContext>();
        services.AddScoped<IEffectiveSiteRoleResolver, UnusedSiteRoleResolver>();
        services.AddSingleton<IPasswordHasher, PasswordHasher>();
        services.AddSingleton<AdminAuthCache>();
        services.AddScoped<IAdminAuthService, AdminAuthService>();
        services.AddAuthentication(IdentityConstants.ApplicationScheme)
            .AddCookie(IdentityConstants.ApplicationScheme)
            .AddCookie(IdentityConstants.TwoFactorUserIdScheme);
        services.AddSingleton<IHttpContextAccessor, HttpContextAccessor>();
        services.AddSingleton<IAuthPolicyOptions, GateHarness.UnrestrictedAuthPolicy>();
        services.AddGatePlumbing();
        var provider = services.BuildServiceProvider();

        using (var scope = provider.CreateScope())
            await scope.ServiceProvider.GetRequiredService<IIdentityBootstrapService>().RunAsync();
        return provider;
    }

    private static async Task<ApplicationUser> FindAsync(IServiceScope scope, string name)
        => (await scope.ServiceProvider.GetRequiredService<UserManager<ApplicationUser>>().FindByNameAsync(name))!;

    private static async Task<ClaimsPrincipal> PrincipalAsync(IServiceScope scope, string name)
        => await scope.ServiceProvider.GetRequiredService<IUserClaimsPrincipalFactory<ApplicationUser>>()
            .CreateAsync(await FindAsync(scope, name));

    private static async Task<SignInOutcome> SignInAsync(ServiceProvider provider, string name, string password)
    {
        using var scope = provider.CreateScope();
        scope.ServiceProvider.GetRequiredService<IHttpContextAccessor>().HttpContext =
            new DefaultHttpContext { RequestServices = scope.ServiceProvider };
        return await scope.ServiceProvider.GetRequiredService<IIdentitySignInService>()
            .PasswordSignInAsync(name, password, rememberMe: false);
    }

    private static async Task CreateAsync(ServiceProvider provider, string name)
    {
        using var scope = provider.AdminScope();
        var result = await scope.ServiceProvider.GetRequiredService<IIdentityAdminService>()
            .CreateUserAsync(name, null, AdminSet, Roles.Viewer);
        result.Succeeded.Should().BeTrue(result.Error);
    }

    [Fact]
    public async Task AnAccountCreatedWithAPasswordIsConfinedUntilItChoosesItsOwn()
    {
        await using var provider = await BuildAsync();
        await CreateAsync(provider, "newcomer");

        (await SignInAsync(provider, "newcomer", AdminSet)).Should().Be(SignInOutcome.RequiresPasswordChange);
        using (var scope = provider.CreateScope())
            (await PrincipalAsync(scope, "newcomer")).IsConfinedToAccountSetup().Should()
                .BeTrue("the admin who typed the password could otherwise use the account");

        string id;
        using (var scope = provider.CreateScope())
            id = (await FindAsync(scope, "newcomer")).Id;
        using (var scope = provider.ScopeAs(id, Roles.Viewer))
        {
            var result = await scope.ServiceProvider.GetRequiredService<IIdentityAdminService>()
                .ChangeOwnPasswordAsync(id, AdminSet, Chosen);
            result.Succeeded.Should().BeTrue(result.Error);
        }

        using (var scope = provider.CreateScope())
            (await PrincipalAsync(scope, "newcomer")).IsConfinedToAccountSetup().Should()
                .BeFalse("the cookie re-issued after the change must open the app");
        (await SignInAsync(provider, "newcomer", Chosen)).Should().Be(SignInOutcome.Success);
    }

    [Fact]
    public async Task AnAdminResettingSomeoneElsesPasswordFlagsIt()
    {
        await using var provider = await BuildAsync();
        await CreateAsync(provider, "resetme");

        string id;
        using (var scope = provider.CreateScope())
        {
            var user = await FindAsync(scope, "resetme");
            id = user.Id;
            user.PasswordIsTemporary = false;
            await scope.ServiceProvider.GetRequiredService<UserManager<ApplicationUser>>().UpdateAsync(user);
        }

        using (var scope = provider.AdminScope())
            (await scope.ServiceProvider.GetRequiredService<IIdentityAdminService>().SetPasswordAsync(id, Chosen))
                .Succeeded.Should().BeTrue();

        using (var scope = provider.CreateScope())
            (await PrincipalAsync(scope, "resetme")).IsConfinedToAccountSetup().Should().BeTrue();
    }

    [Fact]
    public async Task ThePasswordClaimIsNotTheSecondFactorClaim()
    {
        await using var provider = await BuildAsync();
        await CreateAsync(provider, "nofactor");

        using var scope = provider.CreateScope();
        (await PrincipalAsync(scope, "nofactor")).OwesSecondFactor().Should()
            .BeFalse("the redirect would send them to enrol a factor no role asked for");
    }

    [Fact]
    public async Task TheBuiltInAdminsFirstRunPasswordIsNeverConfined()
    {
        await using var provider = await BuildAsync(autoGeneratedAdmin: true);

        using (var scope = provider.CreateScope())
        {
            (await FindAsync(scope, IdentityBootstrapService.AdminUserName)).PasswordIsTemporary.Should().BeTrue();
            (await PrincipalAsync(scope, IdentityBootstrapService.AdminUserName)).IsConfinedToAccountSetup().Should()
                .BeFalse("the auto-generated password keeps its own banners and flow");
        }

        (await SignInAsync(provider, IdentityBootstrapService.AdminUserName, AdminSet)).Should().Be(SignInOutcome.Success);
    }

    [Fact]
    public async Task AnotherAdminResettingTheBuiltInAdminLeavesItUnconfined()
    {
        await using var provider = await BuildAsync(autoGeneratedAdmin: true);

        string id;
        using (var scope = provider.CreateScope())
            id = (await FindAsync(scope, IdentityBootstrapService.AdminUserName)).Id;
        using (var scope = provider.AdminScope())
            (await scope.ServiceProvider.GetRequiredService<IIdentityAdminService>().SetPasswordAsync(id, Chosen))
                .Succeeded.Should().BeTrue();

        using (var scope = provider.CreateScope())
        {
            (await FindAsync(scope, IdentityBootstrapService.AdminUserName)).PasswordIsTemporary.Should().BeFalse();
            (await PrincipalAsync(scope, IdentityBootstrapService.AdminUserName)).IsConfinedToAccountSetup().Should().BeFalse();
        }
    }

    [Fact]
    public async Task AnAdminSettingTheirOwnPasswordThroughTheUsersCardIsNotFlagged()
    {
        await using var provider = await BuildAsync();
        await CreateAsync(provider, "selfadmin");

        string id;
        using (var scope = provider.CreateScope())
            id = (await FindAsync(scope, "selfadmin")).Id;
        using (var scope = provider.ScopeAs(id, Roles.Admin))
            (await scope.ServiceProvider.GetRequiredService<IIdentityAdminService>().SetPasswordAsync(id, Chosen))
                .Succeeded.Should().BeTrue();

        using (var scope = provider.CreateScope())
            (await FindAsync(scope, "selfadmin")).PasswordIsTemporary.Should().BeFalse("nobody else knows it");
    }

    private sealed class UnusedSiteRoleResolver : IEffectiveSiteRoleResolver
    {
        public void Invalidate(string userId) { }

        public void InvalidateAll() { }

        public Task<string?> FirstAdministeredSlugAsync(ClaimsPrincipal user) => Task.FromResult<string?>(null);

        public Task<SiteRole?> GetEffectiveRoleAsync(ClaimsPrincipal user, string slug) => Task.FromResult<SiteRole?>(null);

        public Task<IReadOnlySet<string>> GetAuthorizedSlugsAsync(ClaimsPrincipal user)
            => Task.FromResult<IReadOnlySet<string>>(new HashSet<string>());
    }

    private sealed class NoOpAuditLogger : IAuditLogger
    {
        public void Log(AuditEvent auditEvent) { }
    }

    public void Dispose()
    {
        try
        {
            if (File.Exists(_dbPath)) File.Delete(_dbPath);
        }
        catch (IOException) { /* temp file, ignored */ }
    }
}
