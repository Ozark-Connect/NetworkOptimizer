using NetworkOptimizer.Core.Helpers;
using NetworkOptimizer.Reports;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace NetworkOptimizer.Web.Services.ChangeControl;

/// <summary>
/// Renders a device replacement's Re-cabling Sheet as a PDF, following the Security Audit and
/// Firmware Rollout reports' page setup, branding and table styling (<see cref="PdfReportGenerator"/>).
/// </summary>
public class RecablingPdfGenerator
{
    private readonly BrandingOptions _branding;
    private readonly byte[]? _logoBytes;

    /// <param name="branding">Branding overrides; the product defaults are used when null.</param>
    public RecablingPdfGenerator(BrandingOptions? branding = null)
    {
        _branding = branding ?? BrandingOptions.OzarkConnect();
        QuestPDF.Settings.License = LicenseType.Community;
        _logoBytes = ReportAssets.Logo();
    }

    /// <summary>Renders the sheet to PDF bytes.</summary>
    /// <param name="proposal">The replacement as the Migrate page shows it.</param>
    /// <param name="siteName">Site the device belongs to, used in the subtitle.</param>
    public byte[] GenerateBytes(ReplacementProposal proposal, string siteName)
    {
        ArgumentNullException.ThrowIfNull(proposal);

        var generatedAt = DateTime.Now;
        return Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.Letter);
                page.Margin(0.5f, Unit.Inch);
                page.PageColor(Colors.White);
                page.DefaultTextStyle(x => x.FontSize(9).FontColor(Colors.Black));

                page.Header().Element(c => ComposeHeader(c, proposal, siteName, generatedAt));
                page.Content().Element(c => ComposeContent(c, proposal));
                page.Footer().Element(c => ComposeFooter(c, generatedAt));
            });
        }).GeneratePdf();
    }

    private void ComposeHeader(IContainer container, ReplacementProposal proposal, string siteName, DateTime generatedAt)
    {
        container.Column(column =>
        {
            if (_logoBytes is { Length: > 0 })
                column.Item().AlignLeft().MaxWidth(1.5f, Unit.Inch).Image(_logoBytes);

            column.Item().AlignCenter().Text("Re-cabling Sheet").FontSize(22).Bold().FontColor(_branding.Colors.Primary);
            column.Item().AlignCenter().PaddingTop(2)
                .Text($"{siteName}: {proposal.OldName} ({proposal.OldModel}) to {proposal.NewModel}").FontSize(11);

            column.Item().AlignLeft().PaddingTop(6)
                .Text($"Generated: {generatedAt:MMMM dd, yyyy HH:mm}")
                .FontSize(10).FontColor(Colors.Grey.Medium);

            column.Item().PaddingBottom(10).LineHorizontal(0.5f).LineColor(Colors.Grey.Lighten2);
        });
    }

    private void ComposeContent(IContainer container, ReplacementProposal proposal)
    {
        container.Table(table =>
        {
            table.ColumnsDefinition(c =>
            {
                c.ConstantColumn(150);
                c.RelativeColumn();
                c.ConstantColumn(50);
            });

            var lightGray = _branding.Colors.LightGray;
            table.Header(header =>
            {
                foreach (var heading in new[] { "Old Port to New Port", "Connected", "Done" })
                    header.Cell().Background(lightGray).Padding(6).Text(heading).Bold().FontSize(9);
            });

            foreach (var r in proposal.Recabling)
            {
                Cell(table, $"{r.OldPort} to {r.NewPort}");
                Cell(table, r.Connected, r.Unresolved ? _branding.Colors.Critical : null);
                table.Cell().Border(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(6).AlignCenter()
                    .Width(10).Height(10).Border(0.75f).BorderColor(Colors.Grey.Darken1);
            }
        });
    }

    private void ComposeFooter(IContainer container, DateTime generatedAt)
    {
        container.Column(column =>
        {
            column.Item().LineHorizontal(0.5f).LineColor(Colors.Grey.Lighten2);
            column.Item().PaddingTop(5);

            if (!string.IsNullOrEmpty(_branding.CustomFooter))
            {
                column.Item().AlignCenter().Text(_branding.CustomFooter)
                    .FontSize(8).FontColor(Colors.Grey.Medium);
            }
            else if (_branding.ShowProductAttribution)
            {
                column.Item().AlignCenter().Text(text =>
                {
                    text.Span("Generated by ").FontSize(8).FontColor(Colors.Grey.Medium);
                    text.Span(_branding.ProductName).FontSize(8).FontColor(Colors.Grey.Medium).Bold();
                    text.Span($" for {_branding.CompanyName}").FontSize(8).FontColor(Colors.Grey.Medium);
                    text.Span($" | {generatedAt:yyyy-MM-dd HH:mm}").FontSize(8).FontColor(Colors.Grey.Lighten1);
                });
            }
        });
    }

    private static void Cell(TableDescriptor table, string text, string? fontColor = null)
    {
        var cell = table.Cell().Border(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(6)
            .Text(text).FontSize(9);
        if (fontColor != null) cell.FontColor(fontColor);
    }
}
